import type { FoodItem, MealSuggestion } from '../types';
import { emptyNutrients } from '../types';

const now = Date.UTC(2026, 0, 1);

function food(
  partial: Omit<FoodItem, 'nutrients' | 'createdAt' | 'notes' | 'seeded' | 'imageUrl' | 'barcode' | 'nutriscore' | 'brand'> &
    Partial<Pick<FoodItem, 'brand' | 'barcode' | 'imageUrl' | 'nutriscore' | 'notes'>> & {
      kcal100g: number;
      protein100g: number;
      carbs100g: number;
      fat100g: number;
    },
): FoodItem {
  const { kcal100g, protein100g, carbs100g, fat100g, ...rest } = partial;
  return {
    brand: rest.brand ?? '',
    barcode: rest.barcode ?? null,
    imageUrl: rest.imageUrl ?? null,
    nutriscore: rest.nutriscore ?? null,
    notes: rest.notes ?? '',
    createdAt: now,
    seeded: true,
    id: rest.id,
    name: rest.name,
    store: rest.store,
    estimatedPrice: rest.estimatedPrice,
    defaultGrams: rest.defaultGrams,
    nutrients: {
      ...emptyNutrients(),
      kcal100g,
      protein100g,
      carbs100g,
      fat100g,
    },
  };
}

